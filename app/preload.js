const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('gaz', {
  info: () => ipcRenderer.invoke('info'),
  license: () => ipcRenderer.invoke('license-get'),
  setLicense: (o) => ipcRenderer.invoke('license-set', o),
  getSettings: () => ipcRenderer.invoke('settings-get'),
  setSettings: (s) => ipcRenderer.invoke('settings-set', s),
  pickBook: () => ipcRenderer.invoke('pick-book'),
  openDropped: (file) => ipcRenderer.invoke('open-book-path', webUtils.getPathForFile(file)),
  pickCover: () => ipcRenderer.invoke('pick-cover'),
  languages: (engine, key) => ipcRenderer.invoke('languages', engine, key),
  build: (opts) => ipcRenderer.invoke('build', opts),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  openLink: (u) => ipcRenderer.invoke('open-link', u),
  coverSize: (o) => ipcRenderer.invoke('cover-size', o),
  coverPrompts: (o) => ipcRenderer.invoke('cover-prompts', o),
  coverAi: (o) => ipcRenderer.invoke('cover-ai', o),
  coverSearch: (o) => ipcRenderer.invoke('cover-search', o),
  coverFetch: (url) => ipcRenderer.invoke('cover-fetch', url),
  coverPickFile: () => ipcRenderer.invoke('cover-pick-file'),
  coverPreview: (o) => ipcRenderer.invoke('cover-preview', o),
  geminiKeyPage: () => ipcRenderer.invoke('gemini-key-page'),
  coverExport: (o) => ipcRenderer.invoke('cover-export', o),
  onProgress: (fn) => ipcRenderer.on('progress', (_e, d) => fn(d)),
  openStudio: () => ipcRenderer.invoke('open-studio'),
  openQuick: () => ipcRenderer.invoke('open-quick'),
  // the one-click screens
  quick: {
    pickBook: () => ipcRenderer.invoke('quick-pick-book'),
    dropBook: (file) => ipcRenderer.invoke('quick-open-book', webUtils.getPathForFile(file)),
    pickPhoto: () => ipcRenderer.invoke('quick-pick-photo'),
    dropPhoto: (file) => ipcRenderer.invoke('quick-drop-photo', webUtils.getPathForFile(file)),
    languages: () => ipcRenderer.invoke('quick-languages'),
    make: (o) => ipcRenderer.invoke('quick-make', o),
    gemini: (how, what) => ipcRenderer.invoke('quick-gemini', how, what),
    copy: (text) => ipcRenderer.invoke('quick-copy', text),
    prompt: () => ipcRenderer.invoke('quick-prompt'),
    googlePlay: (what) => ipcRenderer.invoke('quick-google-play', what),
    updateBack: (vals) => ipcRenderer.invoke('quick-update-back', vals),
    finish: () => ipcRenderer.invoke('quick-finish'),
    pickPicture: () => ipcRenderer.invoke('quick-pick-picture'),
    dropPicture: (file) => ipcRenderer.invoke('quick-drop-picture', webUtils.getPathForFile(file)),
    onProgress: (fn) => ipcRenderer.on('quick-progress', (_e, d) => fn(d)),
  },
});
